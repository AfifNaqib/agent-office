import { readFileSync } from 'node:fs';
import { beforeAll, describe, expect, it } from 'vitest';
import { BUILT, buildEmit } from './helpers.js';

describe('built hook script banner', () => {
  beforeAll(() => {
    buildEmit();
  });

  it('starts with a header comment and eslint-disable', () => {
    const lines = readFileSync(BUILT, 'utf8').split('\n');
    expect(lines[0]).toMatch(/^\/\/ Generated by Agent Office/);
    expect(lines[1]).toBe('/* eslint-disable */');
  });
});
